-- [LECTURE_QUESTIONS] 익명 질문 게시판
CREATE TABLE IF NOT EXISTS lecture_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lecture_id TEXT NOT NULL REFERENCES lectures(id) ON DELETE CASCADE,
    client_id TEXT,                                   -- 브라우저별 임의 ID (이름·계정 아님, "내 질문" 표시용)
    content TEXT NOT NULL CHECK (char_length(content) BETWEEN 1 AND 1000),
    is_ai_refined BOOLEAN NOT NULL DEFAULT FALSE,     -- AI가 다듬은 질문으로 보냈는지 (전달 방식 비교용)
    is_resolved BOOLEAN NOT NULL DEFAULT FALSE,       -- 교수자가 답변 완료로 표시
    answer TEXT,                                      -- 교수자 답변 (선택)
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    resolved_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_lecture_questions_lecture_id
    ON lecture_questions (lecture_id, created_at DESC);

-- [LECTURE_NOTICES] 강의 공지 (교수자 대시보드가 생기기 전까지 Supabase Table Editor에서 직접 입력)
-- lecture_id를 비워두면 모든 강의 위젯에 보이는 전체 공지가 됩니다.
CREATE TABLE IF NOT EXISTS lecture_notices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lecture_id TEXT REFERENCES lectures(id) ON DELETE CASCADE,
    category TEXT NOT NULL DEFAULT 'general'
        CHECK (category IN ('important', 'material', 'assignment', 'general')),
    title TEXT NOT NULL,
    content TEXT,
    is_pinned BOOLEAN NOT NULL DEFAULT FALSE,         -- 위젯 상단 고정
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_lecture_notices_lecture_id
    ON lecture_notices (lecture_id, created_at DESC);

-- 개발 편의: 기존 테이블과 같이 RLS 비활성화
ALTER TABLE lecture_questions DISABLE ROW LEVEL SECURITY;
ALTER TABLE lecture_notices DISABLE ROW LEVEL SECURITY;

-- Realtime: 새 질문/공지를 위젯에 바로 반영
ALTER TABLE lecture_questions REPLICA IDENTITY FULL;
ALTER TABLE lecture_notices REPLICA IDENTITY FULL;

DO $$
DECLARE
    t TEXT;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
        CREATE PUBLICATION supabase_realtime;
    END IF;

    -- 이미 등록된 테이블은 건너뜀 (기존 SQL의 ALTER PUBLICATION ... ADD TABLE은 두 번 실행하면 에러)
    FOREACH t IN ARRAY ARRAY['lecture_questions', 'lecture_notices', 'lecture_contents', 'lecture_glossary'] LOOP
        IF NOT EXISTS (
            SELECT 1 FROM pg_publication_tables
            WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = t
        ) THEN
            EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I', t);
        END IF;
    END LOOP;
END $$;

